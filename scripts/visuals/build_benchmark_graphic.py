#!/usr/bin/env python3
"""Render the Knovaryn benchmark summary graphic (contract §6.4) from the
committed benchmark evidence — never from hand-copied numbers.

The script reads ``benchmarks/results/<version>/`` (run-1.json +
aggregate.json) and emits a scheme-stable SVG on the brand's Paper surface,
following docs/design-system/diagrams-and-data-visualization.md:

* only measured facts (rates carry their Wilson 95% intervals and n);
* the mandatory context label — *Offline deterministic framework benchmark —
  not live-model generation throughput*;
* unmeasured things simply do not appear (the `not_measured` map stays in
  the report, where its prose lives).

Usage:
    uv run python scripts/visuals/build_benchmark_graphic.py            # write
    uv run python scripts/visuals/build_benchmark_graphic.py --check    # drift
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RESULTS = REPO / "benchmarks" / "results"
OUT = REPO / "docs" / "assets" / "benchmarks"  # results/ stays runner-owned

# Design tokens (docs/assets/design-system/tokens.css, light values — the
# graphic sits on its own Paper card so it reads on both site schemes).
INK = "#1C2B33"  # --kn-color-text-primary
GRAY_600 = "#55636C"  # --kn-gray-600 (labels)
GRAY_200 = "#D3DADD"  # --kn-color-border (axes, hairlines)
PAPER = "#FBFAF7"  # --kn-color-surface
SUNKEN = "#F1EFE8"  # --kn-color-surface-sunken (context strip)
TRACE = "#0E7C6B"  # --kn-color-brand-primary (bars)
WHITE = "#FFFFFF"  # --kn-gray-0

FONT = "system-ui, -apple-system, 'Segoe UI', Roboto, 'Helvetica Neue', Arial, sans-serif"

CONTEXT_LABEL = "Offline deterministic framework benchmark — not live-model generation throughput"


def _fmt(x: float, nd: int = 3) -> str:
    return f"{x:.{nd}f}"


def _rate_text(name: str, m: dict) -> dict:
    """Label / value-line / bar fraction / CI span for a rate metric."""
    return {
        "label": name,
        "value": f"{_fmt(m['rate'])}  ({m['numerator']}/{m['denominator']})"
        f"   CI {_fmt(m['ci95_low'])}–{_fmt(m['ci95_high'])}",
        "bar": m["rate"],
        "lo": m["ci95_low"],
        "hi": m["ci95_high"],
    }


def build_svg(version: str) -> str:
    rdir = RESULTS / version
    run = json.loads((rdir / "run-1.json").read_text(encoding="utf-8"))
    agg = json.loads((rdir / "aggregate.json").read_text(encoding="utf-8"))

    if agg["runs"] != len(agg["elapsed_s"]["per_run"]):
        raise SystemExit("aggregate runs count does not match recorded repetitions")

    sem = run["semantic_adversarial"]
    pref = run["preference_quality"]
    crash = run["crash_recovery"]
    exports = run["export_round_trip"]

    rates = [
        _rate_text("Semantic false-accept", sem["false_accept"]),
        _rate_text("Semantic false-reject", sem["false_reject"]),
        _rate_text("Preference order-consistency", pref["order_consistency"]),
    ]

    ok_formats = sum(1 for v in exports.values() if v == "ok")
    all_formats = len(exports)
    ms = agg["elapsed_s"]["median"] * 1000.0
    eps = agg["examples_per_second"]["median"]

    stats = [
        (f"{ms:.1f} ms", "median pipeline wall-clock (3 runs)"),
        (f"{eps:.2f} ex/s", "median examples per second"),
        ("H(R₁)=H(R₂)=H(R₃)", "release-bundle SHA-256 identical across runs"),
        (f"{ok_formats}/{all_formats} formats", "export round-trip ok"),
        (
            f"{crash['unique_request_fingerprints']}/{crash['provider_invocations_total']} · "
            f"{crash['duplicate_provider_calls']} dup",
            "crash-resume fingerprints · duplicate calls",
        ),
    ]

    W, H = 880, 640
    MX = 36
    INNER = W - 2 * MX
    e = []  # svg elements

    e.append(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" '
        f'viewBox="0 0 {W} {H}" role="img" aria-labelledby="bg-t bg-d">'
    )
    e.append(f'<title id="bg-t">Knovaryn {version} offline framework benchmark summary</title>')
    e.append(
        '<desc id="bg-d">'
        "Rates with Wilson 95% confidence intervals: semantic false-accept "
        f"{rates[0]['value']}; semantic false-reject {rates[1]['value']}; "
        f"preference order-consistency {rates[2]['value']}. Medians of three "
        f"deterministic runs: {ms:.1f} ms pipeline wall-clock, {eps:.2f} "
        "examples per second, release-bundle SHA-256 identical across runs, "
        f"{ok_formats} of {all_formats} export formats round-trip ok, "
        "crash-resume produced no duplicate provider calls. "
        f"{CONTEXT_LABEL}. Generated from benchmarks/results/{version}/."
        "</desc>"
    )
    e.append(
        "<!-- Generated by scripts/visuals/build_benchmark_graphic.py — do not edit; rerun. -->"
    )
    e.append(f'<rect width="{W}" height="{H}" fill="{PAPER}"/>')
    e.append(
        f'<rect x="1" y="1" width="{W - 2}" height="{H - 2}" fill="none" '
        f'stroke="{GRAY_200}" stroke-width="2" rx="12"/>'
    )

    def esc(s: str) -> str:
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    def text(x, y, s, size, weight, color, anchor="start", spacing=""):
        ls = f' letter-spacing="{spacing}"' if spacing else ""
        e.append(
            f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" '
            f'font-weight="{weight}" fill="{color}" text-anchor="{anchor}"{ls}>'
            f"{esc(s)}</text>"
        )

    # header ------------------------------------------------------------
    y = 46
    text(MX, y, f"BENCHMARK EVIDENCE · KNOVARYN {version}", 11, 600, GRAY_600, spacing="1.5")
    y += 28
    text(MX, y, "Offline framework benchmark summary", 22, 700, INK)
    y += 34

    # mandatory context strip --------------------------------------------
    strip_h = 34
    e.append(
        f'<rect x="{MX}" y="{y - 18}" width="{INNER}" height="{strip_h}" fill="{SUNKEN}" rx="6"/>'
    )
    e.append(f'<circle cx="{MX + 18}" cy="{y}" r="4" fill="{TRACE}"/>')
    text(MX + 32, y + 4, CONTEXT_LABEL, 13, 600, INK)
    y += strip_h + 26

    # quality-gate rates ---------------------------------------------------
    text(MX, y, "QUALITY GATES — RATES WITH WILSON 95% INTERVALS", 11, 600, GRAY_600, spacing="1.5")
    y += 24
    label_x, track_x = MX, MX + 250
    track_w = INNER - 250 - 210
    val_x = track_x + track_w + 14
    row_h = 44
    # axis scale is zero-based, bottom-up: 0 at the block bottom, 1.0 at top

    # axis baseline + frame (zero at bottom, 1.0 at top of block)
    block_top, block_bot = y - 6, y + 3 * row_h - 6
    for frac in (0.0, 0.5, 1.0):
        gy = block_bot - frac * (block_bot - block_top)
        e.append(
            f'<line x1="{track_x}" y1="{gy:.1f}" x2="{track_x + track_w}" '
            f'y2="{gy:.1f}" stroke="{GRAY_200}" stroke-width="1" '
            + ('stroke-dasharray="3 4"/>' if frac else "/>")
        )
        text(track_x - 10, gy + 4, _fmt(frac, 1), 11, 400, GRAY_600, anchor="end")

    for i, r in enumerate(rates):
        cy = y + i * row_h
        text(label_x, cy + 5, r["label"], 14, 500, INK)

        def fx(f: float) -> float:
            return track_x + f * track_w

        # CI whisker behind the bar
        e.append(
            f'<line x1="{fx(r["lo"]):.1f}" y1="{cy - 1}" x2="{fx(r["hi"]):.1f}" '
            f'y2="{cy - 1}" stroke="{INK}" stroke-width="2"/>'
        )
        for bx in (fx(r["lo"]), fx(r["hi"])):
            e.append(
                f'<line x1="{bx:.1f}" y1="{cy - 6}" x2="{bx:.1f}" '
                f'y2="{cy + 4}" stroke="{INK}" stroke-width="2"/>'
            )
        if r["bar"] > 0:
            e.append(
                f'<rect x="{track_x}" y="{cy + 2}" '
                f'width="{fx(r["bar"]) - track_x:.1f}" '
                f'height="12" rx="6" fill="{TRACE}"/>'
            )
        else:
            # zero rate: a dot at zero (never a bar implying magnitude)
            e.append(f'<circle cx="{track_x}" cy="{cy + 8}" r="4" fill="{TRACE}"/>')
        text(val_x, cy + 5, r["value"], 12.5, 400, GRAY_600)
    y += 3 * row_h + 18

    # overhead & reproducibility -------------------------------------------
    e.append(
        f'<line x1="{MX}" y1="{y - 6}" x2="{MX + INNER}" y2="{y - 6}" '
        f'stroke="{GRAY_200}" stroke-width="1"/>'
    )
    text(
        MX,
        y + 18,
        "OVERHEAD & REPRODUCIBILITY — MEDIANS OF 3 DETERMINISTIC RUNS",
        11,
        600,
        GRAY_600,
        spacing="1.5",
    )

    chip_top = y + 40
    cols = 3
    cw = (INNER - 2 * 16) // cols
    ch = 74
    for idx, (big, small) in enumerate(stats):
        cx = MX + (idx % cols) * (cw + 16)
        cy = chip_top + (idx // cols) * (ch + 14)
        e.append(
            f'<rect x="{cx}" y="{cy}" width="{cw}" height="{ch}" rx="8" '
            f'fill="{WHITE}" stroke="{GRAY_200}" stroke-width="1"/>'
        )
        size = 17 if len(big) <= 14 else 14
        text(cx + 14, cy + 30, big, size, 600, INK)
        # wrap the small label onto ≤2 lines
        words, lines, cur = small.split(), [], ""
        for wd in words:
            trial = f"{cur} {wd}".strip()
            if len(trial) > int(cw / 6.1) and cur:
                lines.append(cur)
                cur = wd
            else:
                cur = trial
        lines.append(cur)
        for li, ln in enumerate(lines[:2]):
            text(cx + 14, cy + 48 + li * 14, ln, 11.5, 400, GRAY_600)
    y = chip_top + ((len(stats) + cols - 1) // cols) * (ch + 14) + 22

    # footer -----------------------------------------------------------------
    text(
        MX,
        H - 40,
        f"Source: benchmarks/results/{version}/ · Methodology: "
        "docs/reference/benchmark-methodology.md",
        11.5,
        400,
        GRAY_600,
    )
    text(
        MX,
        H - 22,
        "Live-provider cost/quality: not measured by this runner · Generated by "
        "scripts/visuals/build_benchmark_graphic.py",
        11.5,
        400,
        GRAY_600,
    )

    e.append("</svg>")
    return "\n".join(e) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--version", default="0.2.1")
    ap.add_argument("--check", action="store_true", help="fail on drift, don't write")
    args = ap.parse_args()

    svg = build_svg(args.version)
    out = OUT / f"benchmark-summary-{args.version}.svg"
    out.parent.mkdir(parents=True, exist_ok=True)
    old = out.read_text(encoding="utf-8") if out.exists() else ""
    if args.check:
        if old != svg:
            print(
                f"FAIL: {out.relative_to(REPO)} drifted from the committed "
                "results — rerun scripts/visuals/build_benchmark_graphic.py",
                file=sys.stderr,
            )
            return 1
        print("benchmark graphic up to date with the committed results")
        return 0
    out.write_text(svg, encoding="utf-8")
    print(f"wrote {out.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
