# stem → (source svg, width, height, device_scale)
RASTER_TARGETS = {
    "favicon-32.png": ("favicon.svg", 32, 32, 3),
    "favicon-192.png": ("favicon.svg", 192, 192, 2),
    "app-icon.png": ("favicon.svg", 512, 512, 2),
    "github-avatar.png": ("favicon.svg", 500, 500, 2),
    "github-social-preview.png": ("github-social-preview-source.svg", 1280, 640, 1),
    "docs-social-preview.png": ("docs-social-preview-source.svg", 1200, 630, 1),
    "release-social-preview.png": ("release-social-preview-source.svg", 1200, 630, 1),
}


def _render_png(browser, svg_path: Path, dest: Path, w: int, h: int) -> None:
    html = (
        f'<!doctype html><body style="margin:0">'
        f'<img src="{svg_path.name}" width="{w}" height="{h}"></body>'
    )
    tmp = dest.with_suffix(".html")
    tmp.write_text(html)
    # exact-size raster: device_scale_factor 1 keeps every PNG at its
    # declared pixel dimensions (the SVG is vector, so it stays sharp)
    page = browser.new_page(viewport={"width": w, "height": h}, device_scale_factor=1)
    page.goto(tmp.as_uri())
    page.wait_for_timeout(60)
    page.locator("img").screenshot(path=str(dest))
    page.close()
    tmp.unlink()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify outputs match a fresh build")
    args = ap.parse_args()

    BRAND.mkdir(parents=True, exist_ok=True)
    failures: list[str] = []

    with tempfile.TemporaryDirectory(prefix="knv-brand-") as td:
        tmp = Path(td)
        fresh: dict[str, bytes] = {}
        for name, builder in SVG_TARGETS.items():
            fresh[name] = builder().encode("utf-8")
        for _name, (src, _w, _h, _scale) in RASTER_TARGETS.items():
            (tmp / src).write_bytes(fresh[src])
        from playwright.sync_api import sync_playwright

        with sync_playwright() as p:
            browser = p.chromium.launch()
            for name, (src, w, h, _scale) in RASTER_TARGETS.items():
                _render_png(browser, tmp / src, tmp / name, w, h)
            browser.close()
        for name in RASTER_TARGETS:
            fresh[name] = (tmp / name).read_bytes()

        for name, data in sorted(fresh.items()):
            target = BRAND / name
            if args.check:
                old = target.read_bytes() if target.is_file() else b""
                if hashlib.sha256(old) != hashlib.sha256(data):
                    failures.append(
                        f"{name}: drifted — rerun scripts/visuals/build_brand_assets.py"
                    )
            else:
                target.write_bytes(data)
                print(f"built {name} ({len(data)} bytes)")

    if failures:
        print("\n".join(f"FAIL: {f}" for f in failures), file=sys.stderr)
        return 1
    print("brand assets in sync" if args.check else "all brand assets built")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
