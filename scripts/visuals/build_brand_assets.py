def _paths(d: str | tuple[str, ...], stroke: str, width: float) -> str:
    if isinstance(d, str):
        d = (d,)
    return "".join(f'<path d="{p}" stroke="{stroke}" stroke-width="{width}"/>' for p in d)


def _lowercase(stroke: str) -> str:
    out = []
    for item in LOWERCASE:
        if item.startswith("ELLIPSE"):
            _, cx, cy, rx, ry = item.split()
            out.append(
                f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" '
                f'stroke="{stroke}" stroke-width="7"/>'
            )
        else:
            out.append(f'<path d="{item}" stroke="{stroke}" stroke-width="7"/>')
    return "".join(out)


