#!/usr/bin/env python3
"""Build the complete Knovaryn brand asset family from one source of truth.

Contract §8.4: every brand asset must be reproducible from documented
sources. This script IS that source for the vector family and the raster
derivatives:

* ``logo-primary.svg``          — horizontal lockup, light backgrounds
* ``logo-primary-dark.svg``     — horizontal lockup, dark backgrounds
* ``logo-stacked.svg``          — symbol above wordmark
* ``logo-symbol.svg``           — the Tracemark mark alone
* ``logo-wordmark.svg``         — wordmark alone (ink)
* ``logo-monochrome-dark.svg``  — single-ink lockup (light backgrounds)
* ``logo-monochrome-light.svg`` — single-paper lockup (dark backgrounds)
* ``favicon.svg``               — mark on an ink tile
* ``favicon-32.png`` / ``favicon-192.png`` / ``app-icon.png``
* ``github-avatar.png``
* ``github-readme-banner.svg`` / ``github-readme-banner-dark.svg``
* ``github-readme-banner-narrow.svg`` / ``github-readme-banner-narrow-dark.svg``
* ``github-social-preview-source.svg`` / ``github-social-preview.png``
* ``docs-social-preview.png`` / ``release-social-preview.png``

The letterforms are original monoline geometry (no font dependency, no
embedded raster, no external references). Rasters are rendered with
Playwright's Chromium at fixed device-scale factors — same inputs, same
bytes on any machine with the pinned browser.

Usage:
    uv run --extra visuals python scripts/visuals/build_brand_assets.py
    uv run --extra visuals python scripts/visuals/build_brand_assets.py --check
"""

