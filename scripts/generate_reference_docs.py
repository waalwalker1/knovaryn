# ------------------------------------------------------------------ plumbing


def _replace_block(text: str, begin: str, end: str, rendered: str, target_desc: str) -> str:
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    body = rendered.rstrip("\n")
    if begin in text and end in text:
        return pattern.sub(lambda _m: body, text)
    print(f"note: no markers in {target_desc}; appending block", file=sys.stderr)
    return text.rstrip("\n") + "\n\n" + body + "\n"


def build_all() -> dict[Path, str]:
    """Path → final file content for every generated surface."""
    files: dict[Path, str] = {}
    files[DOCS / "rest-api.md"] = render_rest_api()
    files[DOCS / "mcp-tools.md"] = render_mcp_catalogue()
    files[DOCS / "quality-gates.md"] = render_quality_gates()
    files[DOCS / "profiles.md"] = render_profiles()
    files[DOCS / "claim-matrix.md"] = render_claim_matrix()

    exp_path = DOCS / "exporters.md"
    exp_text = _replace_block(
        exp_path.read_text(encoding="utf-8"),
        _begin("EXPORT FORMATS"),
        _end("EXPORT FORMATS"),
        render_export_formats(),
        str(exp_path.relative_to(REPO_ROOT)),
    ) if exp_path.exists() else None
    if exp_text is not None:
        files[exp_path] = exp_text

    cfg_path = DOCS / "config.md"
    cfg_text = _replace_block(
        cfg_path.read_text(encoding="utf-8"),
        _begin("CONFIG DEFAULTS"),
        _end("CONFIG DEFAULTS"),
        render_config_defaults(),
        str(cfg_path.relative_to(REPO_ROOT)),
    ) if cfg_path.exists() else None
    if cfg_text is not None:
        files[cfg_path] = cfg_text
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail on drift, don't write")
    ap.add_argument("--quiet", action="store_true", help="suppress per-file output")
    args = ap.parse_args()

    # importing the REST/MCP apps prints banner noise; keep stdout clean
    buf = io.StringIO()
    with redirect_stdout(buf):
        files = build_all()

    drifted: list[str] = []
    for path, content in sorted(files.items()):
        old = path.read_text(encoding="utf-8") if path.exists() else ""
        if old != content:
            drifted.append(str(path.relative_to(REPO_ROOT)))
            if not args.check and not args.quiet:
                path.write_text(content, encoding="utf-8")
                print(f"wrote {path.relative_to(REPO_ROOT)}")

    if args.check:
        if drifted:
            print(
                "FAIL: generated reference docs drifted from the code:\n  - "
                + "\n  - ".join(drifted)
                + "\nRun: python scripts/generate_reference_docs.py  (then commit)",
                file=sys.stderr,
            )
            return 1
        print("generated reference docs are up to date with the code")
        return 0

    print(f"done ({len(files)} files, {len(drifted)} updated)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
