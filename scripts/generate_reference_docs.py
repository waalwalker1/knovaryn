REPO_ROOT = Path(__file__).resolve().parent.parent
DOCS = REPO_ROOT / "docs" / "reference"

BANNER = (
    "<!-- GENERATED by scripts/generate_reference_docs.py from the real code."
    " Do not edit inside this block: rerun the script instead. -->"
)


def _begin(tag: str) -> str:
    return f"<!-- BEGIN GENERATED {tag} -->"


def _end(tag: str) -> str:
    return f"<!-- END GENERATED {tag} -->"


# ---------------------------------------------------------------- surfaces --

def render_rest_api() -> str:
    from knovaryn.interfaces.rest.app import app as rest_app

    schema = rest_app.openapi()
    rows = []
    for path, methods in sorted(schema.get("paths", {}).items()):
        for method in sorted(methods):
            if method.startswith(("x-", "parameters")):
                continue
            op = methods[method]
            rows.append((method.upper(), path, op.get("summary", "")))
    out = [
        "# Reference — REST API",
        "",
        BANNER,
        "",
        "Endpoints below are generated from the live OpenAPI schema of",
        "`knovaryn.interfaces.rest.app` — the same app `knovaryn server` serves.",
        "Interactive docs ship at `/docs` and `/openapi.json` on a running server.",
        "",
        "When `KNOVARYN_API_TOKEN` is set, every route except the `/v1/health`",
        "probe requires a bearer token with the listed scope(s); see",
        "[security hardening](../security/hardening.md). Error bodies are redacted.",
        "",
        "| Method | Path | Summary |",
        "|---|---|---|",
    ]
    for method, path, summary in rows:
        out.append(f"| `{method}` | `{path}` | {summary or '—'} |")
    return "\n".join(out) + "\n"


def render_mcp_catalogue() -> str:
    from knovaryn.interfaces.mcp.server import build_server

    server = build_server()

    async def _tools():
        return await server.list_tools()

    tools = asyncio.run(_tools())
    rows = sorted(((t.name, (t.description or "").strip().splitlines()[0]
                    if (t.description or "").strip() else "—") for t in tools))
    out = [
        "# Reference — MCP tools",
        "",
        BANNER,
        "",
        "Generated from the Knovaryn MCP server's real tool registration",
        "(`build_server().list_tools()`), so names and counts cannot drift from",
        "what an MCP client actually sees over stdio or streamable HTTP.",
        "",
        f"{len(rows)} registered tools:",
        "",
        "| Tool | Description |",
        "|---|---|",
    ]
    for name, desc in rows:
        out.append(f"| `{name}` | {desc} |")
    out += [
        "",
        "Run with `knovaryn mcp` (stdio by default; `--transport streamable-http`",
        "for remote use behind the bearer-token guard). See",
        "[MCP clients](../guides/mcp-clients.md).",
    ]
    return "\n".join(out) + "\n"


def render_quality_gates() -> str:
    from knovaryn.pipeline.quality.validators import PreferenceValidator, default_validators

    validators = list(default_validators()) + [PreferenceValidator()]
    seen: dict[str, str] = {}
    for v in validators:
        doc = (type(v).__doc__ or "").strip().splitlines()
        seen.setdefault(v.name, doc[0] if doc else "—")
    out = [
        "# Reference — Quality gates",
        "",
        BANNER,
        "",
        "Generated from validator registration (`default_validators()` plus the",
        "preference validator). Every accepted example must pass the enabled",
        "gates; failures carry machine-readable reason codes routed to review or",
        "quarantine. See [quality concepts](../concepts/quality-gates.md).",
        "",
        "| Gate | Purpose |",
        "|---|---|",
    ]
    for name, desc in sorted(seen.items()):
        out.append(f"| `{name}` | {desc} |")
    return "\n".join(out) + "\n"


def render_profiles() -> str:
    from knovaryn.pipeline.quality.profiles import (
        PROFILE_CERTIFIED_PAIRWISE,
        PROFILE_HEURISTIC,
        SPECS,
    )

    out = [
        "# Reference — Validation profiles",
        "",
        BANNER,
        "",
        "Generated from the semantic-profile registry and preference-profile",
        "constants. Exactly these profiles exist; unknown values are rejected at",
        "configuration time.",
        "",
        "## Semantic validation profiles (`quality.semantic_profile`)",
        "",
        "| Profile | Model judge | Network | Limits |",
        "|---|---|---|---|",
    ]
    for name in sorted(SPECS):
        spec = SPECS[name]
        limits = (spec.limits or "").replace("|", "\\|").replace("\n", " ")
        out.append(
            f"| `{name}` | {'yes' if spec.uses_model_judge else 'no'} "
            f"| {'required' if spec.network_required else 'none'} | {limits} |"
        )
    out += [
        "",
        "`offline-fast` is the default and runs anywhere; `certified-semantic`",
        "additionally consults a cited-evidence-only LLM judge through the model",
        "gateway. Deterministic contradictions are final in both profiles; an",
        "unavailable judge yields *unverified*, never *verified*. Benchmark",
        "false-accept/false-reject rates with confidence intervals are published",
        "in the committed benchmark report (`benchmarks/report-0-1-0.md`) — do",
        "not describe results as certified without reproducing them.",
        "",
        "## Preference profiles (`preference.profile`)",
        "",
        "| Profile | Behaviour |",
        "|---|---|",
        f"| `{PROFILE_HEURISTIC}` | Deterministic checks only (default): length band, artifact separability, topology sanity. |",
        f"| `{PROFILE_CERTIFIED_PAIRWISE}` | Adds the certified two-order pairwise judge: randomized presentation, reversed repeat, minimum preference margin, rejected-defect classification; disagreements route to review and full judge lineage is recorded. |",
    ]
    return "\n".join(out) + "\n"


def render_export_formats() -> str:
    from knovaryn.pipeline.export.formats import MEDIA_TYPES, SUPPORTED_FORMATS

    tag = "EXPORT FORMATS"
    lines = [
        _begin(tag),
        "",
        "Format ids are generated from `pipeline.export.formats.SUPPORTED_FORMATS`",
        "— this table cannot drift from what `--format` accepts:",
        "",
        "| Format | Media type |",
        "|---|---|",
    ]
    for fmt in sorted(SUPPORTED_FORMATS):
        lines.append(f"| `{fmt}` | `{MEDIA_TYPES[fmt]}` |")
    lines += [
        f"| `jsonl` | `{MEDIA_TYPES['jsonl']}` |",
        "",
        "`jsonl` is the canonical passthrough (accepted by `--format` alongside",
        "the ids above). Parquet is **not** a `--format` id: it is produced by",
        "the SDK function `knovaryn.pipeline.export.export_parquet` (requires the",
        "`parquet` extra) and by the release bundle's split files when that extra",
        "is installed.",
        "",
        _end(tag),
    ]
    return "\n".join(lines)


def render_config_defaults() -> str:
    from knovaryn.domain.config import _DEFAULTS

    def flatten(prefix: str, node: object, into: list[tuple[str, str]]) -> None:
        if isinstance(node, dict):
            for k, v in sorted(node.items()):
                key = f"{prefix}.{k}" if prefix else str(k)
                flatten(key, v, into)
        else:
            text = json.dumps(node) if not isinstance(node, str) else json.dumps(node)
            into.append((prefix, text))

    pairs: list[tuple[str, str]] = []
    flatten("", dict(_DEFAULTS), pairs)

    tag = "CONFIG DEFAULTS"
    lines = [
        _begin(tag),
        "",
        "Defaults generated from `knovaryn.domain.config._DEFAULTS` — the single",
        "authoritative settings source. `${ENV}` placeholders resolve from the",
        "environment (`KNOVARYN_` prefix).",
        "",
        "| Key | Default |",
        "|---|---|",
    ]
    for key, value in pairs:
        lines.append(f"| `{key}` | `{value}` |")
    lines += ["", _end(tag)]
    return "\n".join(lines)


