"""Generate canonical reference documentation from the code (defect 3.4 / §5.1).

Every public reference surface below is rendered from the real registration
point, never hand-maintained:

* REST endpoints        ← FastAPI OpenAPI schema      → docs/reference/rest-api.md
* MCP tool catalogue    ← server tool registration    → docs/reference/mcp-tools.md
* Quality gates         ← default_validators()        → docs/reference/quality-gates.md
* Validation profiles   ← semantic/preference profile registries
                                                      → docs/reference/profiles.md
* Export formats        ← SUPPORTED_FORMATS           → docs/reference/exporters.md (block)
* Configuration keys    ← _DEFAULTS                   → docs/reference/config.md  (block)

Usage:
    python scripts/generate_reference_docs.py            # rewrite in place
    python scripts/generate_reference_docs.py --check    # exit 1 on drift (CI)
"""

from __future__ import annotations

